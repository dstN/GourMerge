/**
 * GourMerge — Shared Type Definitions
 *
 * These types are auto-imported by both `app/` and `server/` via the `shared/` directory.
 * They define the canonical data shapes for the entire application.
 */

// ── Units ─────────────────────────────────────────────────────

/** Canonical units stored in the database (metric-only for mass/volume) */
export type CanonicalUnit = 'g' | 'ml' | 'piece' | 'pinch' | 'tsp' | 'tbsp'

/** Display units available in the frontend (includes imperial) */
export type DisplayUnit = CanonicalUnit | 'cup' | 'oz' | 'floz' | 'lb' | 'kg' | 'l'

/** User's preferred measurement system */
export type MeasurementSystem = 'metric' | 'imperial'

// ── Ingredient ────────────────────────────────────────────────

export interface Ingredient {
  id: number
  name: string
  /** JSON object with locale keys: { en: "Flour", de: "Mehl" } */
  nameTranslations: Record<string, string>
  category: string | null
  createdAt: string
}

export interface CommitIngredient {
  id: number
  commitId: number
  ingredientId: number
  ingredient?: Ingredient
  quantity: number
  unit: CanonicalUnit
  notes: string | null
  sortOrder: number
}

// ── Recipe Step ───────────────────────────────────────────────

export interface CommitStep {
  id: number
  commitId: number
  sortOrder: number
  /** Markdown content generated by TipTap */
  content: string
}

// ── Commit ────────────────────────────────────────────────────

export interface RecipeCommit {
  id: number
  branchId: number
  parentCommitId: number | null
  authorId: number
  message: string
  createdAt: string
  /** Populated on demand */
  ingredients?: CommitIngredient[]
  /** Populated on demand */
  steps?: CommitStep[]
}

// ── Branch ────────────────────────────────────────────────────

export interface RecipeBranch {
  id: number
  recipeId: number
  name: string
  headCommitId: number | null
  isDefault: boolean
  createdAt: string
}

// ── Recipe (Repository) ───────────────────────────────────────

export interface Recipe {
  id: number
  ownerId: number
  title: string
  description: string | null
  visibility: 'public' | 'private'
  forkedFromRecipeId: number | null
  servings: number
  prepTimeMinutes: number | null
  cookTimeMinutes: number | null
  difficulty: 'easy' | 'medium' | 'hard'
  /** Populated on demand */
  branches?: RecipeBranch[]
  starCount: number
  forkCount: number
  createdAt: string
  updatedAt: string
}

// ── GourMerge Request ─────────────────────────────────────────

export type GourmergeRequestStatus = 'open' | 'closed' | 'merged' | 'draft'

export interface GourmergeRequest {
  id: number
  recipeId: number
  authorId: number
  title: string
  description: string | null
  status: GourmergeRequestStatus
  sourceBranchId: number
  targetBranchId: number
  /** For cross-repo GourMerge Requests (from forks) */
  sourceRecipeId: number | null
  createdAt: string
  updatedAt: string
}

export interface GourmergeRequestComment {
  id: number
  gourmergeRequestId: number
  authorId: number
  body: string
  createdAt: string
  updatedAt: string
}

// ── Diff Types ────────────────────────────────────────────────

export type DiffChangeType = 'added' | 'removed' | 'modified' | 'unchanged'

export interface IngredientDiffEntry {
  type: DiffChangeType
  ingredientId: number
  ingredientName: string
  /** Only present for 'removed' and 'modified' */
  oldQuantity?: number
  oldUnit?: CanonicalUnit
  /** Only present for 'added' and 'modified' */
  newQuantity?: number
  newUnit?: CanonicalUnit
  /** Only present for 'modified' — what exactly changed */
  changes?: ('quantity' | 'unit')[]
}

export interface TextDiffSegment {
  /** -1 = deletion, 0 = equal, 1 = insertion */
  type: -1 | 0 | 1
  text: string
}

export interface StepDiffEntry {
  type: DiffChangeType
  sortOrder: number
  /** Raw old Markdown (for 'removed' and 'modified') */
  oldContent?: string
  /** Raw new Markdown (for 'added' and 'modified') */
  newContent?: string
  /** Fine-grained text diff segments (for 'modified') */
  segments?: TextDiffSegment[]
}

export interface CommitDiff {
  ingredients: IngredientDiffEntry[]
  steps: StepDiffEntry[]
  summary: {
    ingredientsAdded: number
    ingredientsRemoved: number
    ingredientsModified: number
    stepsAdded: number
    stepsRemoved: number
    stepsModified: number
  }
}

// ── User ──────────────────────────────────────────────────────

export interface User {
  id: number
  username: string
  displayName: string | null
  email: string
  avatarUrl: string | null
  bio: string | null
  preferredLocale: string
  preferredMeasurementSystem: MeasurementSystem
  createdAt: string
}
